/** 用户可编辑的默认文本（契约段收敛成 {{输出格式}} 占位符）。 */
const EDITABLE_DEFAULTS: Record<string, string> = {};
/** 固定契约段文本（含 {{反馈字段}} 等占位符，渲染时按本套风格取值）。 */
const FORMAT_BLOCKS: Record<string, string> = {};

/** 契约段拆分：从 FORMAT_HEAD 到下一个空行+【标题】之前。 */
function splitFormatSection(text: string): { editable: string; format: string } {
  const i = text.indexOf(FORMAT_HEAD);
  if (i < 0) return { editable: text, format: '' };
  const j = text.indexOf('\n\n【', i);
  const end = j < 0 ? text.length : j;
  return { editable: `${text.slice(0, i)}${FORMAT_TOKEN}${text.slice(end)}`, format: text.slice(i, end) };
}

for (const key of Object.keys(DEFAULTS)) {
  const { editable, format } = splitFormatSection(DEFAULTS[key]);
  EDITABLE_DEFAULTS[key] = editable;
  FORMAT_BLOCKS[key] = format;
}


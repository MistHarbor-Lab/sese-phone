export function socialStyleKeyOf(style: PhoneStyle | undefined): SocialStyleKey {
  return style === 'xianxia' ? 'xianxia' : style === 'wuxia' ? 'wuxia' : style === 'fantasy' ? 'fantasy' : 'modern';
}

/** 反向：风格键 → PhoneStyle（编辑器 UI 复用 skins 的风格化名词时用）。 */
export function socialStyleOf(key: SocialStyleKey): PhoneStyle {
  return key === 'modern' ? '' : key;
}

/** 提示词覆盖键（`kind:style:branch`）。 */
export function socialPromptKey(kind: SocialKindKey, style: PhoneStyle | undefined, branch: SocialBranchKey): string {
  return `${kind}:${socialStyleKeyOf(style)}:${branch}`;
}

/** 选题池覆盖键（`kind:style`；选题全风格共用同一池，不分指令分支）。 */
export function socialThemeKey(kind: SocialKindKey, style: PhoneStyle | undefined): string {
  return `${kind}:${socialStyleKeyOf(style)}`;
}


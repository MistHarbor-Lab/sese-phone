/**
 * 渲染一套模板：契约段先注入（内容永远取内置默认，用户覆盖文本改动不了它），
 * 再替换其余占位符（未列出的 {{...}} 原样保留，{{user}}/{{me}} 等酒馆宏不受影响）。
 */
export function renderSocialPromptTemplate(key: string, template: string, vars: SocialPromptVars): string {
  const format = FORMAT_BLOCKS[key] ?? '';
  const merged = format ? template.split(FORMAT_TOKEN).join(format) : template;
  return merged.replace(TOKEN_RE, (m, name: string) => (TOKEN_NAMES.has(name) ? (vars[name] ?? '') : m));
}
